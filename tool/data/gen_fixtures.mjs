// Generates (1) the parsha-schedule lookup table used by the app and
// (2) test fixtures that validate the app's own Hebrew calendar and zmanim
// code.
//
//   cd tool/data && npm ci && node gen_fixtures.mjs
//
// @hebcal/core is used here only as an independent reference ("oracle") at
// build time. Nothing from it is shipped in the app: the app's calendar is
// implemented from first principles in lib/core/calendar/, and the tests in
// test/core/calendar/ check it against these fixtures.
//
// The schedule of weekly readings depends only on the "type" of the Hebrew
// year (weekday of Rosh Hashana and the year's length) and on Israel vs. the
// Diaspora — this is how the Tur (OC 428) enumerates it. We record, for every
// year type, which reading falls on each Shabbat of the year, and verify that
// every year of the same type over seven centuries agrees.

import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {
  CandleLightingEvent,
  HDate,
  HavdalahEvent,
  HebrewCalendar,
  Location,
  Sedra,
  flags,
  parshiot,
} from '@hebcal/core';
import {getLeyningOnDate} from '@hebcal/leyning';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const fixturesDir = path.join(root, 'test', 'fixtures');
fs.mkdirSync(fixturesDir, {recursive: true});

const iso = (hd) => {
  const d = hd.greg();
  const y = d.getFullYear();
  const s = String(Math.abs(y)).padStart(4, '0');
  return `${y < 0 ? '-' : ''}${s}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
};

function write(rel, data) {
  const file = path.join(root, rel);
  fs.writeFileSync(file, typeof data === 'string' ? data : JSON.stringify(data) + '\n');
  process.stdout.write(`wrote ${rel} (${(fs.statSync(file).size / 1024).toFixed(0)} KB)\n`);
}

// Encodes a Shabbat reading: 0 = holiday (no weekly portion), n = parsha #n,
// -n = parsha #n combined with #n+1.
function code(res) {
  if (res.chag) return 0;
  const idx = parshiot.indexOf(res.parsha[0]) + 1;
  if (idx <= 0) throw new Error(`unknown parsha ${res.parsha}`);
  return res.parsha.length === 2 ? -idx : idx;
}

// ---------------------------------------------------------------------------
// 1. Parsha table + schedule fixture

const FIRST = 5500; // 1739 CE
const LAST = 6200; // 2439 CE
const table = new Map();
const scheduleFixture = {};
for (let y = FIRST; y <= LAST; y++) {
  const rh = new HDate(1, 'Tishrei', y);
  const len = HDate.daysInYear(y);
  for (const il of [false, true]) {
    const sedra = new Sedra(y, il);
    const seq = [];
    let d = rh.onOrAfter(6);
    const nextRh = new HDate(1, 'Tishrei', y + 1);
    for (; d.deltaDays(nextRh) < 0; d = d.add(7, 'd')) seq.push(code(sedra.lookup(d)));
    const key = `${rh.getDay()}_${len}_${il ? 'il' : 'd'}`;
    const prev = table.get(key);
    if (prev && prev.join() !== seq.join()) throw new Error(`year ${y} disagrees with its type ${key}`);
    table.set(key, seq);
    if (y >= 5700 && y <= 5900) (scheduleFixture[il ? 'il' : 'diaspora'] ||= {})[y] = seq;
  }
}
write('test/fixtures/parsha_schedule.json', scheduleFixture);

const dartLines = [
  '// GENERATED by tool/data/gen_fixtures.mjs — do not edit by hand.',
  '//',
  '// Weekly readings for each Shabbat of a Hebrew year, starting with the',
  '// first Shabbat on or after Rosh Hashana, keyed by',
  '// "<weekday of Rosh Hashana (0=Sun)>_<days in year>_<il|d>".',
  '// 0 = a festival Shabbat with no weekly portion, n = parsha #n (1-based),',
  '// -n = parsha #n read together with #n+1.',
  '',
  'const Map<String, List<int>> parshaTable = {',
  ...[...table.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `  '${k}': [${v.join(', ')}],`),
  '};',
  '',
];
write('lib/core/calendar/parsha_table.g.dart', dartLines.join('\n'));
process.stdout.write(`${table.size} year types\n`);

// ---------------------------------------------------------------------------
// 2. Hebrew date conversion fixtures

const years = [];
for (let y = FIRST; y <= LAST; y++) {
  years.push([y, iso(new HDate(1, 'Tishrei', y)), HDate.daysInYear(y), HDate.isLeapYear(y) ? 1 : 0]);
}
const samples = [];
{
  let d = new HDate(new Date(1750, 0, 1));
  const end = new HDate(new Date(2400, 0, 1));
  for (; d.deltaDays(end) < 0; d = d.add(97, 'd')) {
    samples.push([iso(d), d.getFullYear(), d.getMonth(), d.getDate()]);
  }
}
write('test/fixtures/hebrew_calendar.json', {years, samples, months: 'Nisan=1 ... Adar=12, Adar II=13'});

// ---------------------------------------------------------------------------
// 3. Festival days on which work is forbidden (Yom Tov), Israel vs. Diaspora

const yomTov = {};
for (let y = 5780; y <= 5800; y++) {
  for (const il of [false, true]) {
    const evs = HebrewCalendar.calendar({
      year: y, isHebrewYear: true, il, noMinorFast: true, noModern: true,
      noRoshChodesh: true, noSpecialShabbat: true, shabbatMevarchim: false,
    });
    const days = [...new Set(evs.filter((e) => e.getFlags() & flags.CHAG).map((e) => iso(e.getDate())))].sort();
    (yomTov[il ? 'il' : 'diaspora'] ||= {})[y] = days;
  }
}
write('test/fixtures/yom_tov.json', yomTov);

// ---------------------------------------------------------------------------
// 4. Special haftarot (Shekalim, Rosh Chodesh, Chanukah, ...)

const special = {diaspora: [], il: []};
for (const il of [false, true]) {
  let d = new HDate(new Date(2000, 0, 1)).onOrAfter(6);
  const end = new HDate(new Date(2100, 0, 1));
  for (; d.deltaDays(end) < 0; d = d.add(7, 'd')) {
    const res = new Sedra(d.getFullYear(), il).lookup(d);
    if (res.chag) continue;
    const l = getLeyningOnDate(d, il);
    special[il ? 'il' : 'diaspora'].push([iso(d), l?.reason?.haftara ?? null]);
  }
}
// Keep only non-null entries plus the date range, to keep the fixture small.
const compact = {};
for (const k of Object.keys(special)) {
  compact[k] = {
    from: special[k][0][0],
    to: special[k][special[k].length - 1][0],
    special: Object.fromEntries(special[k].filter(([, r]) => r).map(([date, r]) => [date, r])),
  };
}
write('test/fixtures/special_haftarot.json', compact);

// ---------------------------------------------------------------------------
// 5. Candle-lighting and Havdalah for places in assets/data/cities.json
// (run tool/data/build_cities.mjs first), over two years: Shabbat and Yom
// Tov, Israel and the Diaspora, both hemispheres, daylight-saving changes
// and a clock far from its longitude (Honolulu, Auckland). None is far
// enough north for nightfall to vanish in summer; near that latitude the
// time swings by minutes with the slightest difference in the sun's
// position, so the tests check those places on their own.

const ZMANIM_CITIES = [
  281184, // Jerusalem (40 minutes)
  293397, // Tel Aviv (20 minutes, as elsewhere in Israel)
  294801, // Haifa (30 minutes)
  293067, // Zikhron Ya'akov (30 minutes)
  295530, // Beersheba
  295277, // Eilat
  5128581, // New York City
  5100280, // Lakewood
  5368361, // Los Angeles
  4887398, // Chicago
  4164138, // Miami
  6167865, // Toronto
  6077243, // Montreal
  2643743, // London
  2643123, // Manchester
  2988507, // Paris
  2803138, // Antwerp
  524901, // Moscow
  993800, // Johannesburg
  2158177, // Melbourne
  3435910, // Buenos Aires
  3530597, // Mexico City
  5856195, // Honolulu
  2193733, // Auckland
];

{
  const {cities} = JSON.parse(fs.readFileSync(path.join(root, 'assets', 'data', 'cities.json'), 'utf8'));
  const from = new Date(2026, 0, 1);
  const to = new Date(2027, 11, 31);
  const out = {from: '2026-01-01', to: '2027-12-31', cities: []};
  for (const id of ZMANIM_CITIES) {
    const city = cities.find((c) => c.id === id);
    if (!city) throw new Error(`no city ${id} in cities.json`);
    const il = city.cc === 'IL';
    const location = new Location(city.lat, city.lon, il, city.tz, city.name_en, city.cc, String(city.id));
    const options = (candleLightingMins) => ({
      start: from, end: to, location, il, candlelighting: true, candleLightingMins,
      noMinorFast: true, noModern: true, noRoshChodesh: true, noSpecialShabbat: true, shabbatMevarchim: false,
    });
    // Hebcal has its own minutes for Israel (by GeoNames id for Jerusalem,
    // Haifa and Zikhron Ya'akov): the list must agree.
    const events = HebrewCalendar.calendar(options(city.candleMinutes));
    const own = HebrewCalendar.calendar(options(undefined));
    const first = (evs) => evs.find((e) => e instanceof CandleLightingEvent).eventTime.getTime();
    if (first(events) !== first(own)) throw new Error(`${city.name_en}: candle-lighting minutes differ from Hebcal's`);

    // Minutes after the midnight that begins the event's date, on the
    // place's clock (1440 or more after the next midnight).
    const clock = new Intl.DateTimeFormat('en-CA', {
      timeZone: city.tz, year: 'numeric', month: '2-digit', day: '2-digit',
      hour: '2-digit', minute: '2-digit', hourCycle: 'h23',
    });
    const minutesAfter = (isoDate, time) => {
      const p = Object.fromEntries(clock.formatToParts(time).map(({type, value}) => [type, value]));
      const days = (Date.UTC(+p.year, +p.month - 1, +p.day) - Date.parse(`${isoDate}T00:00:00Z`)) / 86400000;
      return days * 1440 + +p.hour * 60 + +p.minute;
    };
    const times = new Map();
    for (const ev of events) {
      if (!(ev instanceof CandleLightingEvent) && !(ev instanceof HavdalahEvent)) continue;
      // Candles are lit before sunset on a Friday, even on Yom Tov; after
      // Shabbat, and from an existing flame on a second night of Yom Tov, at
      // nightfall, the time of Havdalah.
      const day = ev.getDate().getDay();
      const atNightfall =
        ev instanceof HavdalahEvent || (day !== 5 && (day === 6 || (ev.getFlags() & flags.LIGHT_CANDLES_TZEIS) !== 0));
      const date = iso(ev.getDate());
      times.set(`${date}|${atNightfall ? 'h' : 'c'}`, [date, atNightfall ? 'h' : 'c', minutesAfter(date, ev.eventTime)]);
    }
    out.cities.push({id: city.id, name: city.name_en, times: [...times.values()]});
  }
  write('test/fixtures/zmanim.json', out);
}
